def main(out):
    rgb = [((v >> 16) & 255, (v >> 8) & 255, v & 255) for v in PAL]
    grey = []
    for k in range(16):
        g = k * 17
        grey.append(rgb.index((g, g, g)))
    inv = bytearray(32768)
    for i in range(32768):
        r, g, b = (i >> 10) & 31, (i >> 5) & 31, i & 31
        r, g, b = r * 255 // 31, g * 255 // 31, b * 255 // 31
        best, bd = 0, 1 << 30
        for k, (pr, pg, pb) in enumerate(rgb):
            d = 2 * (r - pr) ** 2 + 4 * (g - pg) ** 2 + 3 * (b - pb) ** 2
            if d < bd:
                best, bd = k, d
        inv[i] = best
    with open(out, 'w') as f:
        f.write('/* pppal.h - made by tools/mkpal.py: do not edit */\n')
        f.write('static const unsigned long pp_pal[256] = {\n')
        for i in range(0, 256, 8):
            f.write('\t' + ', '.join('0x%06x' % v for v in PAL[i:i + 8]) + ',\n')
        f.write('};\nstatic const unsigned char pp_grey8[16] = { %s };\n' % ', '.join(map(str, grey)))
        f.write('static const unsigned char pp_inverse[32768] = {\n')
        for i in range(0, 32768, 32):
            f.write(','.join(map(str, inv[i:i + 32])) + ',\n')
        f.write('};\n')


if __name__ == '__main__':
    main(sys.argv[1])
